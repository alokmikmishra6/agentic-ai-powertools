// Keep browsing lightweight: full article bodies and project code load with their pages.
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { ARTICLES, DOMAINS, PILLARS, THINKING } from '../src/data/content.js'
import { FORMATS } from '../src/data/editorial.js'
import { plainText } from '../src/lib/article-content.js'
import { PROJECTS } from '../src/lib/showcase.js'

const articles = ARTICLES.map(({ body, ...metadata }) => ({ ...metadata, format: FORMATS[metadata.slug] || "Deep dive" }))
const projects = PROJECTS.map(({ slug, title, tag, problem }) => ({ slug, title, tag, problem }))
const output = new URL('../src/data/index.js', import.meta.url)
const source = '// Generated by scripts/build-index.mjs. Edit content through npm run build:content.\n'
  + 'export const ARTICLES = ' + JSON.stringify(articles, null, 2) + ';\n\n'
  + 'export const PROJECTS = ' + JSON.stringify(projects, null, 2) + ';\n\n'
  + 'export const DOMAINS = ' + JSON.stringify(DOMAINS, null, 2) + ';\n\n'
  + 'export const PILLARS = ' + JSON.stringify(PILLARS, null, 2) + ';\n\n'
  + 'export const THINKING = ' + JSON.stringify(THINKING, null, 2) + ';\n'
if (!existsSync(output) || readFileSync(output, 'utf8') !== source) writeFileSync(output, source)
console.log(`Content index ready: ${articles.length} essays, ${projects.length} projects.`)

const searchSource = JSON.stringify(Object.fromEntries(ARTICLES.map(a => [a.slug, plainText(a.body)])))
const searchOutput = new URL('../src/data/search-index.json', import.meta.url)
if (!existsSync(searchOutput) || readFileSync(searchOutput, 'utf8') !== searchSource) writeFileSync(searchOutput, searchSource)
